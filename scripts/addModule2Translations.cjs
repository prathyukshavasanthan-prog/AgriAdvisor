for (const [lang, newKeys] of Object.entries(translations)) {
  const filePath = path.join(localesDir, `${lang}.json`);
  if (!fs.existsSync(filePath)) {
    console.error(`Locale file missing: ${filePath}`);
    continue;
  }
  const original = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  const merged = { ...original, ...newKeys };
  fs.writeFileSync(filePath, JSON.stringify(merged, null, 2) + '\n', 'utf-8');
  console.log(`Updated ${lang}.json with ${Object.keys(newKeys).length} Module 2 keys.`);
  updatedCount++;
}

console.log(`Successfully updated all ${updatedCount} locale files!`);
