const languages = ['en', 'ta', 'hi', 'te', 'kn', 'ml', 'mr', 'bn', 'gu', 'pa'];

for (const lang of languages) {
  const filePath = path.join(localesDir, `${lang}.json`);
  if (!fs.existsSync(filePath)) {
    console.error(`Missing file: ${filePath}`);
    continue;
  }
  const current = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const additions = module4Translations[lang] || module4Translations.en;
  
  let added = 0;
  for (const [key, value] of Object.entries(additions)) {
    current[key] = value;
    added++;
  }
  
  fs.writeFileSync(filePath, JSON.stringify(current, null, 2) + '\n', 'utf8');
  console.log(`[${lang}] Injected ${added} Module 4 keys. Total keys now: ${Object.keys(current).length}`);
}

